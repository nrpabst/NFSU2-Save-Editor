// Regenerates src/data.js from a finished (100%) NFSU2 profile.
// Usage: node tools/extract-data.js tests/fixtures/100pct.bin
const fs = require("fs");
const path = require("path");
const src = process.argv[2];
if (!src) { console.error("usage: node tools/extract-data.js <100% profile>"); process.exit(1); }
const d = fs.readFileSync(src);
const u32 = o => d.readUInt32LE(o);
const bh = s => { let r = 0xFFFFFFFF; for (const c of s) r = (Math.imul(r, 33) + c.charCodeAt(0)) >>> 0; return r; };
const CARS = "PEUGOT FOCUS COROLLA 240SX MIATA CIVIC PEUGOT106 CORSA HUMMER NAVIGATOR ESCALADE TIBURON SENTRA CELICA IS300 SUPRA GOLF A3 RSX ECLIPSE TT RX8 350Z G35 3000GT GTO MUSTANGGT SKYLINE LANCEREVO8 RX7 IMPREZAWRX".split(" ");
const XN = new Map(CARS.map(c => [bh(c), c]));

// Every used career slot (2034 bytes from 22636) and My Cars slot (1072 bytes from 1196) with
// performance upgrades becomes a preset (stock cars add nothing).
const blocks = [];
for (let i = 0; i < 5; i++) { const b = 22636 + i * 2034; if (d[b + 1069] === 1) blocks.push(["career", b]); }
for (let i = 0; i < 20; i++) { const b = 1196 + i * 1072; if (d[b + 8] === 1) blocks.push(["quick race", b]); }
const PRESETS = blocks.filter(([, b]) => d.subarray(b + 780, b + 856).some(x => x)).map(([srcKind, b]) => ({ code: XN.get(u32(b + 24)), src: srcKind, data: d.subarray(b, b + 1072).toString("base64") }));

// Part values that appear on two or more different car models are treated as generic (usable on any car).
const seen = {};
for (const p of PRESETS) {
  const blk = Buffer.from(p.data, "base64");
  for (let off = 28; off < 708; off += 4) {
    const h = blk.readUInt32LE(off); if (!h) continue;
    ((seen[off] = seen[off] || {})[h] = seen[off][h] || new Set()).add(p.code);
  }
}
const OBS_GENERIC = {};
for (const off in seen) { const g = Object.entries(seen[off]).filter(([, s]) => s.size >= 2).map(([h]) => +h); if (g.length) OBS_GENERIC[off] = g; }

// Maxed performance: floats at +708..748 and flags at +780..856 of the first Quick Race car.
const q = 1196;
const MAXPERF = d.subarray(q + 708, q + 748).toString("hex") + "|" + d.subarray(q + 780, q + 856).toString("hex");
// Career progress block and per-car unlock values.
const PROGRESS100 = d.subarray(39266, 53780).toString("base64");
const CAR_UNLOCKS100 = Array.from({ length: 31 }, (_, r) => u32(44 + r * 24));

const out = "// Generated by tools/extract-data.js from a 100% save. Do not edit by hand.\n" +
  `var PRESETS=${JSON.stringify(PRESETS)};\nvar OBS_GENERIC=${JSON.stringify(OBS_GENERIC)};\n` +
  `var PROGRESS100=${JSON.stringify(PROGRESS100)};\nvar MAXPERF=${JSON.stringify(MAXPERF)};\nvar CAR_UNLOCKS100=${JSON.stringify(CAR_UNLOCKS100)};\n` +
  'if (typeof module !== "undefined") module.exports = { PRESETS, OBS_GENERIC, PROGRESS100, MAXPERF, CAR_UNLOCKS100 };\n';
fs.writeFileSync(path.join(__dirname, "..", "src", "data.js"), out);
console.log(`wrote src/data.js: ${PRESETS.length} presets, ${Object.keys(OBS_GENERIC).length} generic slots`);
